import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const source=ts.transpileModule(readFileSync(new URL('../lib/auth-identity.ts',import.meta.url),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const {resolveProfileIdentity,IdentityConflict}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const sqlite=new DatabaseSync(':memory:');
sqlite.exec(readFileSync(new URL('../drizzle/0000_first_storm.sql',import.meta.url),'utf8'));
sqlite.exec(readFileSync(new URL('../drizzle/0001_melted_steve_rogers.sql',import.meta.url),'utf8'));
const db={prepare(sql){return {bind(...values){return {async first(){return sqlite.prepare(sql).get(...values)??null;},async run(){return sqlite.prepare(sql).run(...values);}};}};}};
sqlite.prepare('INSERT INTO profiles VALUES(?,?,?,?)').run('original-id','anna','anna@example.test','Anna');
sqlite.prepare('INSERT INTO kitchens VALUES(?,?,?,?)').run('kitchen','Family','original-id','2026-09-16');
sqlite.prepare('INSERT INTO members VALUES(?,?)').run('kitchen','original-id');
assert.equal(await resolveProfileIdentity(db,'subject-a',' ANNA@example.test '),'original-id');
assert.equal(sqlite.prepare('SELECT owner FROM kitchens').get().owner,'original-id');
assert.equal(sqlite.prepare('SELECT user_id FROM members').get().user_id,'original-id');
assert.equal(await resolveProfileIdentity(db,'subject-a','changed@example.test'),'original-id');
await assert.rejects(()=>resolveProfileIdentity(db,'subject-b','anna@example.test'),IdentityConflict);
assert.equal(await resolveProfileIdentity(db,'subject-c','new@example.test'),'supabase:subject-c');
assert.deepEqual(await Promise.all([resolveProfileIdentity(db,'subject-d','d@example.test'),resolveProfileIdentity(db,'subject-d','d@example.test')]),['supabase:subject-d','supabase:subject-d']);
sqlite.close();
console.log('7 authentication migration checks passed: existing ownership, kitchen membership, stable identity, conflicting identity, new profile and concurrent mapping.');
